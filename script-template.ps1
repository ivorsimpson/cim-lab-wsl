# ============================================================================
# new-cuda-project.ps1   (single-file edition)
# ----------------------------------------------------------------------------
# One-shot bootstrap for a CUDA C++ project on a Sussex lab Windows machine.
#
# Student workflow:
#     .\new-cuda-project.ps1 -Name my-first-kernel
#
# What it does, in order:
#   1. Validates the project name.
#   2. Checks WSL is enabled on this machine (fails fast with IT message if not).
#   3. Ensures the "LabGPU" WSL distro exists; provisions it if absent.
#   4. Ensures the CUDA toolkit is installed inside LabGPU; installs if absent.
#   5. Creates the project folder + writes all template files inside WSL.
#   6. Opens the project in VS Code via WSL-remote.
#
# This single-file version embeds all bash scripts and template files as
# here-strings. They are extracted to a temporary directory at run time,
# pushed into WSL with correct (LF) line endings, and executed.
#
# Re-running with the same name is safe: the script is idempotent up to
# step 5, where it refuses to overwrite an existing project unless -Force.
#
# Why WSL? CUDA C++ on Windows needs MSVC as the host compiler, and MSVC
# needs Visual Studio (admin). WSL sidesteps that — apt installs the toolkit
# user-mode and g++ is the host compiler. The only one-time admin step is
# enabling WSL itself (IT runs `wsl --install --no-distribution` once per
# machine); after that, students provision distros + install CUDA bits
# entirely user-mode.
#
# Prerequisites (one-time, done by IT, with admin rights):
#   - WSL enabled:   wsl --install --no-distribution    (then reboot)
#   - NVIDIA Windows driver with WSL passthrough (any post-2021 driver)
#   - VS Code installed (user-mode installer is fine, no admin needed)
#
# ----------------------------------------------------------------------------
# THIS FILE IS GENERATED BY build.ps1 FROM script-template.ps1 + template/.
# Do not edit the distributed script directly — edit the sources and rebuild.
# ============================================================================

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [string]$Name,

    [Parameter()]
    [ValidateSet('cuda')]
    [string]$Type = 'cuda',

    [Parameter()]
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

# ============================================================================
# CONFIGURATION
# ============================================================================

$DistroName        = 'LabGPU'
$DistroInstallDir  = Join-Path $env:LOCALAPPDATA "WSL\$DistroName"
$DistroTarballURL  = 'https://cloud-images.ubuntu.com/wsl/jammy/current/ubuntu-jammy-wsl-amd64-ubuntu22.04lts.rootfs.tar.gz'
$CudaToolkitVer    = '12.8'   # major.minor — apt package name is cuda-toolkit-12-8
$ProjectsRoot      = 'projects'

