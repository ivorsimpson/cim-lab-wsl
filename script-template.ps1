# Single-quoted here-strings (@'...'@) preserve everything literally — no
# variable interpolation, no escaping of $ or `. Placeholders like
# __PROJECT_NAME__ are substituted on the Linux side by sed.
#
# The here-strings below are populated at build time by build.ps1 from the
# files in linux/ and template/. The {{TEMPLATE: ...}} markers are the
